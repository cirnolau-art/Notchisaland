import XCTest
import AppKit
@testable import NotchIsland

final class ModuleClipboardTests: XCTestCase {
    private func preferences(_ run: (IslandPreferences) -> Void) {
        let suite = "NotchIsland.modules.test.\(UUID())"
        let defaults = UserDefaults(suiteName: suite)!
        defer { defaults.removePersistentDomain(forName: suite) }
        run(IslandPreferences(defaults: defaults))
    }
    private func board(_ run: (NSPasteboard, ClipboardHistory) -> Void) {
        let board = NSPasteboard(name: .init("NotchIsland.clipboard.test.\(UUID())"))
        defer { board.releaseGlobally() }
        let history = ClipboardHistory(board: board, frontApp: { "test.app" })
        run(board, history)
    }
    private func write(_ text: String, to board: NSPasteboard) { board.clearContents(); board.setString(text, forType: .string) }
    func testDefaultsPreserveExistingModulesAndClipboardIsOptIn() {
        preferences { prefs in
            XCTAssertEqual(prefs.visibleTabs, [.music, .files, .timer, .audio, .calendar, .shortcuts, .focus])
            XCTAssertFalse(prefs.isEnabled(.clipboard))
            prefs.setEnabled(.files, false); prefs.setEnabled(.clipboard, true)
            XCTAssertEqual(prefs.resolvedTab(.files), .music)
            XCTAssertFalse(prefs.visibleTabs.contains(.files)); XCTAssertTrue(prefs.visibleTabs.contains(.clipboard))
            XCTAssertTrue(prefs.isEnabled(.timer))
            for tab in IslandTab.allCases { prefs.setEnabled(tab, false) }
            XCTAssertTrue(prefs.visibleTabs.isEmpty); XCTAssertNil(prefs.resolvedTab(.music))
        }
    }
    func testModuleReconciliationPreservesActiveHUDAndRingingAlarm() {
        var policy = PresentationPolicy(); policy.open(.music); XCTAssertTrue(policy.showTransient())
        policy.reconcileTabs([.files, .clipboard]); XCTAssertEqual(policy.surface, .panel(.files)); XCTAssertTrue(policy.transientVisible)
        policy.reconcileTabs([]); XCTAssertEqual(policy.surface, .idle); XCTAssertTrue(policy.transientVisible)
        policy.expireTransient(); XCTAssertFalse(policy.transientVisible)
        policy.ring(); policy.reconcileTabs([]); XCTAssertEqual(policy.surface, .alert)
    }
    func testNavigationSkipsDisabledModulesHandlesSingleAndEmpty() {
        let visible: [IslandTab] = [.files, .calendar, .clipboard]
        XCTAssertEqual(IslandTab.files.moved(by: -1, among: visible), .clipboard)
        XCTAssertEqual(IslandTab.clipboard.moved(by: 1, among: visible), .files)
        XCTAssertEqual(IslandTab.files.moved(by: 100, among: visible), .calendar)
        XCTAssertEqual(IslandTab.music.moved(by: 1, among: visible), .files)
        XCTAssertEqual(IslandTab.calendar.moved(by: -1, among: [.calendar]), .calendar)
        XCTAssertEqual(IslandTab.calendar.moved(by: 1, among: []), .calendar)
    }
    func testEnablingDoesNotReadExistingClipboardAndOffDoesNotCapture() {
        board { board, history in
            write("existing", to: board); history.capture(); XCTAssertTrue(history.entries.isEmpty)
            history.setEnabled(true, schedule: false); history.capture(); XCTAssertTrue(history.entries.isEmpty)
            write("new", to: board); history.capture(); XCTAssertEqual(history.entries.first?.text, "new")
            history.setEnabled(false); XCTAssertTrue(history.entries.isEmpty)
            XCTAssertEqual(board.string(forType: .string), "new")
            write("off", to: board); history.capture(); XCTAssertTrue(history.entries.isEmpty)
            history.setEnabled(true, schedule: false); history.capture(); XCTAssertTrue(history.entries.isEmpty)
        }
    }
    func testDeduplicationCopyRemoveAndClearDoNotEraseSystemClipboard() {
        board { board, history in
            history.setEnabled(true, schedule: false)
            for text in ["first", "second", "first"] { write(text, to: board); history.capture() }
            XCTAssertEqual(history.entries.compactMap(\.text), ["first", "second"])
            let id = history.entries[1].id
            XCTAssertTrue(history.copy(id)); XCTAssertEqual(board.string(forType: .string), "second")
            history.capture(); XCTAssertEqual(history.entries.count, 2)
            history.remove(id); XCTAssertFalse(history.copy(id)); XCTAssertEqual(history.entries.count, 1)
            history.clear(); XCTAssertTrue(history.entries.isEmpty); XCTAssertEqual(board.string(forType: .string), "second")
        }
    }
    func testConfidentialMarkersAndPasswordManagersAreIgnored() {
        board { board, history in
            history.setEnabled(true, schedule: false)
            for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
                write("secret", to: board); board.setData(Data(), forType: .init(type)); history.capture()
                XCTAssertTrue(history.entries.isEmpty)
            }
            for app in ["com.1password.1password", "com.apple.Passwords"] {
                let privateHistory = ClipboardHistory(board: board, frontApp: { app })
                privateHistory.setEnabled(true, schedule: false); write("unmarked secret", to: board); privateHistory.capture()
                XCTAssertTrue(privateHistory.entries.isEmpty)
            }
        }
    }
    func testCountAndByteCapsAndOversizedInputs() {
        board { board, history in
            history.setEnabled(true, schedule: false)
            for index in 0..<50 { write("entry \(index)", to: board); history.capture() }
            XCTAssertEqual(history.entries.count, 30); XCTAssertEqual(history.entries.first?.text, "entry 49")
            write(String(repeating: "a", count: 1024 * 1024 + 1), to: board); history.capture()
            XCTAssertEqual(history.entries.count, 30)
            history.clear()
            for index in 0..<8 {
                var data = Data(repeating: UInt8(index), count: 3 * 1024 * 1024)
                data.replaceSubrange(0..<4, with: [0x89, 0x50, 0x4e, 0x47])
                board.clearContents(); board.setData(data, forType: .png); history.capture()
            }
            XCTAssertEqual(history.entries.count, 5)
            XCTAssertLessThanOrEqual(history.entries.reduce(0, { $0 + $1.byteCount }), ClipboardHistory.byteLimit)
        }
    }
    func testImageRoundTripsAndFilesDoNotPolluteHistory() {
        board { board, history in
            history.setEnabled(true, schedule: false)
            let data = Data([0x89, 0x50, 0x4e, 0x47, 0, 1, 2])
            board.clearContents(); board.setData(data, forType: .png); history.capture()
            XCTAssertEqual(history.entries.first?.imageData, data)
            XCTAssertTrue(history.copy(history.entries[0].id)); XCTAssertEqual(board.data(forType: .png), data)
            board.clearContents(); board.writeObjects([NSURL(fileURLWithPath: "/tmp/example.txt")]); history.capture()
            XCTAssertEqual(history.entries.count, 1)
        }
    }
    func testGlassOpaquePlateauCoversNotchAndStopsRemainOrdered() {
        for height: CGFloat in [116, 192, 280, 364] {
            let stops = IslandBackdropView.tintStops(height: height, notchHeight: 38)
            XCTAssertEqual(stops.first, 0); XCTAssertEqual(stops.last, 1)
            XCTAssertEqual(stops, stops.sorted())
            XCTAssertGreaterThanOrEqual(stops[1] * height, 41)
        }
    }
}

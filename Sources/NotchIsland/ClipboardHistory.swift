import AppKit
import ImageIO

struct ClipboardEntry: Identifiable, Equatable {
    let id: UUID
    let date: Date
    let text: String?
    let imageData: Data?
    var byteCount: Int { text?.utf8.count ?? imageData?.count ?? 0 }
    var preview: String { text.map { String($0.prefix(240)).replacingOccurrences(of: "\n", with: "  ") } ?? "图片" }
}

/// Opt-in, bounded, memory-only history. Enabling begins with the next copy, never the existing board.
final class ClipboardHistory {
    var onChange: (() -> Void)?
    private(set) var entries: [ClipboardEntry] = []
    private(set) var enabled = false
    private var timer: Timer?
    private let board: NSPasteboard
    private let frontApp: () -> String?
    private var changeCount = 0
    static let limit = 30
    static let byteLimit = 16 * 1024 * 1024
    init(board: NSPasteboard = .general, frontApp: @escaping () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier }) {
        self.board = board; self.frontApp = frontApp
    }
    deinit { timer?.invalidate() }
    func setEnabled(_ value: Bool, schedule: Bool = true) {
        guard value != enabled else { return }
        enabled = value; timer?.invalidate(); timer = nil; changeCount = board.changeCount
        if value && schedule {
            let timer = Timer(timeInterval: 0.8, repeats: true) { [weak self] _ in self?.capture() }
            timer.tolerance = 0.2; self.timer = timer; RunLoop.main.add(timer, forMode: .common)
        } else if !value { clear() }
    }
    func capture() {
        guard enabled, board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        let types = board.types ?? []
        let markers = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "com.typeit4me.clipping"]
        let app = frontApp()?.lowercased() ?? ""
        guard !markers.contains(where: { types.contains(NSPasteboard.PasteboardType($0)) }),
              !["1password", "onepassword", "bitwarden", "keychainaccess", "keepass", "dashlane", "strongbox", "com.apple.passwords"].contains(where: { app.contains($0) }),
              !types.contains(.fileURL) else { return }
        let entry: ClipboardEntry
        if let data = board.data(forType: .png) ?? board.data(forType: .tiff) {
            guard !data.isEmpty, data.count <= 4 * 1024 * 1024 else { return }
            entry = .init(id: UUID(), date: Date(), text: nil, imageData: data)
        } else if let data = board.data(forType: .string), data.count <= 1024 * 1024,
                  let text = String(data: data, encoding: .utf8), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            entry = .init(id: UUID(), date: Date(), text: text, imageData: nil)
        } else { return }
        // Copying the same value again moves it to the top, without duplicate records.
        entries.removeAll { $0.text == entry.text && $0.imageData == entry.imageData }
        entries.insert(entry, at: 0)
        while entries.count > Self.limit || entries.reduce(0, { $0 + $1.byteCount }) > Self.byteLimit { entries.removeLast() }
        onChange?()
    }
    @discardableResult func copy(_ id: UUID) -> Bool {
        guard enabled, let entry = entries.first(where: { $0.id == id }) else { return false }
        // Write the stored bytes using their original representation; avoid inflating image data.
        let item = NSPasteboardItem()
        if let text = entry.text { item.setString(text, forType: .string) }
        else if let data = entry.imageData { item.setData(data, forType: data.starts(with: [0x89, 0x50, 0x4e, 0x47]) ? .png : .tiff) }
        else { return false }
        board.clearContents(); let result = board.writeObjects([item]); changeCount = board.changeCount
        return result
    }
    func remove(_ id: UUID) { entries.removeAll { $0.id == id }; onChange?() }
    func clear() { guard !entries.isEmpty else { return }; entries.removeAll(); onChange?() }
}

final class ClipboardPanelView: ActivityPanel {
    var history: ClipboardHistory?
    var onInteraction: (() -> Void)?
    private let list = NSScrollView()
    private var key: [UUID]?
    private var countLabel: NSTextField!
    private var feedback: NSTextField!
    override init(frame: NSRect) {
        super.init(frame: frame)
        let width = bounds.width
        text("剪贴板", NSRect(x: 26, y: 7, width: 150, height: 24), size: 17, weight: .semibold)
        countLabel = text("", NSRect(x: width - 156, y: 12, width: 93, height: 17), size: 11, alpha: 0.45); countLabel.alignment = .right
        action(symbol: "trash", help: "清空剪贴板历史", rect: NSRect(x: width - 54, y: 3, width: 30, height: 30)) { [weak self] in self?.history?.clear(); self?.onInteraction?() }
        list.frame = NSRect(x: 16, y: 43, width: width - 32, height: 196)
        list.drawsBackground = false; list.hasVerticalScroller = true; list.scrollerStyle = .overlay; addSubview(list)
        feedback = text("点击重新复制 · 仅在本次运行中保留", NSRect(x: 26, y: 254, width: width - 52, height: 17), size: 11, alpha: 0.42)
    }
    required init?(coder: NSCoder) { fatalError() }
    func update() {
        let entries = history?.entries ?? []
        guard key != entries.map(\.id) else { return }; key = entries.map(\.id)
        countLabel.stringValue = "\(entries.count) / 30 条"
        feedback.stringValue = "点击重新复制 · 仅在本次运行中保留"
        let document = ActivityPanel(frame: NSRect(x: 0, y: 0, width: list.bounds.width - 4, height: max(196, CGFloat(entries.count) * 60)))
        if entries.isEmpty {
            document.icon("doc.on.clipboard", NSRect(x: document.bounds.midX - 19, y: 32, width: 38, height: 38), alpha: 0.6)
            let title = document.text("下一次复制，就会出现在这里", NSRect(x: 8, y: 93, width: document.bounds.width - 16, height: 23), size: 15, weight: .medium); title.alignment = .center
            let note = document.text("支持文字与图片 · 关闭模块即清空历史", NSRect(x: 8, y: 128, width: document.bounds.width - 16, height: 18), size: 11, alpha: 0.45); note.alignment = .center
        }
        for (index, entry) in entries.enumerated() {
            let row = ActivityPanel(frame: NSRect(x: 0, y: CGFloat(index) * 60, width: document.bounds.width, height: 56))
            row.wantsLayer = true; row.layer?.cornerRadius = 11; row.layer?.backgroundColor = NSColor.white.withAlphaComponent(0.04).cgColor
            if let data = entry.imageData,
               let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
               let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: 96, kCGImageSourceCreateThumbnailWithTransform: true] as CFDictionary) {
                let image = NSImage(cgImage: cg, size: NSSize(width: cg.width, height: cg.height))
                let thumbnail = NSImageView(frame: NSRect(x: 10, y: 9, width: 38, height: 38)); thumbnail.image = image; thumbnail.imageScaling = .scaleProportionallyUpOrDown; thumbnail.wantsLayer = true; thumbnail.layer?.cornerRadius = 6; thumbnail.layer?.masksToBounds = true; row.addSubview(thumbnail)
            } else { row.icon("text.alignleft", NSRect(x: 17, y: 18, width: 22, height: 22), alpha: 0.55) }
            row.text(entry.preview, NSRect(x: 60, y: 8, width: row.bounds.width - 102, height: 22), size: 12, weight: .medium)
            let time = DateFormatter.localizedString(from: entry.date, dateStyle: .none, timeStyle: .short)
            row.text("\(entry.text == nil ? "图片" : "文字") · \(time)", NSRect(x: 60, y: 33, width: row.bounds.width - 106, height: 16), size: 10, alpha: 0.45)
            row.action(help: "重新复制这条记录", rect: NSRect(x: 0, y: 0, width: row.bounds.width - 40, height: 56)) { [weak self] in
                guard let self else { return }
                self.feedback.stringValue = self.history?.copy(entry.id) == true ? "已复制 · 切换到目标应用后粘贴" : "复制失败，请重试"
                self.onInteraction?()
            }
            row.action(symbol: "xmark", help: "删除这条记录", rect: NSRect(x: row.bounds.width - 35, y: 14, width: 26, height: 26)) { [weak self] in self?.history?.remove(entry.id); self?.onInteraction?() }.symbolSize = 10
            document.addSubview(row)
        }
        list.documentView = document
    }
}
